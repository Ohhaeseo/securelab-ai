-- V2: 보안 이벤트 (접근 거부, CSRF 거부 등)
-- 기획서 컬럼 + 보완 사항 I-3 (reason_code, resource_type, resource_id, ip_address)
-- 요청 본문·문서 내용·비밀번호는 저장하지 않는다. 판정 코드와 식별자만 남긴다.

CREATE TABLE security_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT,
    event_type    VARCHAR(40)  NOT NULL,
    severity      VARCHAR(10)  NOT NULL,
    action        VARCHAR(20)  NOT NULL,
    reason_code   VARCHAR(40),
    resource_type VARCHAR(40),
    resource_id   VARCHAR(255),
    ip_address    VARCHAR(45),
    request_id    VARCHAR(64),
    occurred_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_security_events_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_security_events_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH'))
);

CREATE INDEX idx_security_events_type_time ON security_events (event_type, occurred_at);
CREATE INDEX idx_security_events_time ON security_events (occurred_at);
