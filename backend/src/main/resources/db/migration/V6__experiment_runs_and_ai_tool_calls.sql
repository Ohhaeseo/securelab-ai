-- V6: 실험 결과(experiment_runs)와 AI 도구 호출 감사(ai_tool_calls) — 보완 사항 I-2
-- 기획서 7장: "모델 반응"과 "실제 행위"를 따로 기록한다. 기획서의 success 하나 대신
-- model_complied(모델 반응)과 action_executed(실제 침해, ASR 기준)로 나눈다.

CREATE TABLE experiment_runs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id     BIGINT      NOT NULL,
    session_id      BIGINT,
    target          VARCHAR(20) NOT NULL,
    defense_enabled BOOLEAN     NOT NULL,
    -- AI 시나리오: 모델이 악성 지시를 따른 출력을 냈는가 (API 시나리오는 NULL)
    model_complied  BOOLEAN,
    -- 보안 목표가 실제로 침해됐는가 (무단 조회·변경·실행·유출). ASR은 이 값으로 계산한다.
    action_executed BOOLEAN     NOT NULL,
    policy_code     VARCHAR(40),
    http_status     SMALLINT,
    latency_ms      INTEGER,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_experiment_runs_scenario FOREIGN KEY (scenario_id) REFERENCES attack_scenarios (id),
    CONSTRAINT fk_experiment_runs_session FOREIGN KEY (session_id) REFERENCES ai_sessions (id),
    CONSTRAINT ck_experiment_runs_target CHECK (target IN ('VULNERABLE', 'PROTECTED'))
);

CREATE INDEX idx_experiment_runs_scenario_time ON experiment_runs (scenario_id, created_at);

-- 모델이 제안한 도구 호출. 허용 목록 밖 이름도 그대로 기록한다(AI-04). 인자는 원문 대신 SHA-256만 남긴다.
-- decision: PROPOSED(실행 정책 도입 전, 실행 안 함) / ALLOWED / DENIED (7주차 정책 게이트)
CREATE TABLE ai_tool_calls (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT       NOT NULL,
    tool_name   VARCHAR(100) NOT NULL,
    args_digest VARCHAR(64),
    decision    VARCHAR(10)  NOT NULL,
    reason_code VARCHAR(40),
    request_id  VARCHAR(64),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_ai_tool_calls_session FOREIGN KEY (session_id) REFERENCES ai_sessions (id),
    CONSTRAINT ck_ai_tool_calls_decision CHECK (decision IN ('PROPOSED', 'ALLOWED', 'DENIED'))
);

CREATE INDEX idx_ai_tool_calls_session_time ON ai_tool_calls (session_id, created_at);
