-- V4: 로그인 시도 기록 (SEC-03)
-- 평문 이메일·비밀번호는 저장하지 않는다. email_digest = HMAC-SHA256(서버 비밀키, 정규화 이메일)의 16진수 (I-5).
-- 보존 기간이 지나면 정리 작업이 지운다.

CREATE TABLE login_attempts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT,
    email_digest VARCHAR(64)  NOT NULL,
    ip_address   VARCHAR(45),
    success      BOOLEAN      NOT NULL,
    -- 차단 중이라 비밀번호를 검증하지 않고 거부한 시도
    blocked      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_login_attempts_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_login_attempts_digest CHECK (email_digest ~ '^[0-9a-f]{64}$')
);

CREATE INDEX idx_login_attempts_created_at ON login_attempts (created_at);
CREATE INDEX idx_login_attempts_ip_time ON login_attempts (ip_address, created_at);
CREATE INDEX idx_login_attempts_digest_ip_time ON login_attempts (email_digest, ip_address, created_at);
