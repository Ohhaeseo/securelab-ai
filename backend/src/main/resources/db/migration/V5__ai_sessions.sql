-- V5: AI 문서 도우미 세션 (M5)
-- 질문·답변·문서 원문은 저장하지 않는다 (기획서 5장). 세션 메타데이터만 남긴다.

CREATE TABLE ai_sessions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    model_name VARCHAR(100) NOT NULL,
    status     VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_ai_sessions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_ai_sessions_status CHECK (status IN ('ACTIVE', 'CLOSED'))
);

CREATE INDEX idx_ai_sessions_user_time ON ai_sessions (user_id, created_at);
